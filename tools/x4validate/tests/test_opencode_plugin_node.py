@pytest.fixture
def oc(tmp_path):
    """(tk, env): a sandbox toolkit with the generated .opencode/ copied in."""
    tmp, tk, env = make_sandbox(tmp_path)
    for sub in ("hooks", "plugins"):
        shutil.copytree(REPO / ".opencode" / sub, tk / ".opencode" / sub,
                        ignore=shutil.ignore_patterns("__pycache__"))
    env = dict(env, X4_PYTHON=sys.executable, X4_OPENCODE_SHELL="bash")
    return tk, env


def drive(tk, env, steps, timeout=180):
    case = {"ctx": {"directory": str(tk), "worktree": str(tk)}, "steps": steps}
    cf = tk / "case.json"
    cf.write_text(json.dumps(case), encoding="utf-8")
    r = subprocess.run([NODE, str(DRIVER), str(tk / ".opencode" / "plugins" / "x4guard.js"), str(cf)],
                       capture_output=True, env=env, timeout=timeout)
    assert r.returncode == 0, r.stderr.decode("utf-8", "replace")
    return json.loads(r.stdout.decode("utf-8").strip().splitlines()[-1])


def before(tool, args, call="c1"):
    return {"hook": "tool.execute.before", "input": {"tool": tool, "sessionID": "s", "callID": call},
            "output": {"args": args}}


def after(tool, args, call="c1", out="done"):
    return {"hook": "tool.execute.after", "input": {"tool": tool, "sessionID": "s", "callID": call, "args": args},
            "output": {"title": "", "output": out, "metadata": {}}}


