"""The OpenCode plugin (Plan 3 lane L Task 5): .opencode/plugins/x4guard.js is TRANSPORT only --
find Python, run .opencode/hooks/opencode_adapter.py with a bound, accept ONE `X4OK {...}` line,
throw on deny -- and fails CLOSED on everything it controls.

Driven under node (fixtures/opencode/drive-plugin.mjs). OpenCode runs plugins under Bun, and
whether OpenCode honours the throw is READ from its docs and source, never run here (user
decision: no local install). node is required on CI; off CI its absence is a counted skip.
"""
