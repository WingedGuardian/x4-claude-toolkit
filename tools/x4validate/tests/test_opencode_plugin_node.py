STUBS = {
    "garbage": "print('hello')",
    "two_lines": "print('X4OK {\"v\":1,\"decision\":\"allow\",\"inert\":false,\"reason\":null,\"context\":null}')\n"
                 "print('X4OK {\"v\":1,\"decision\":\"allow\",\"inert\":false,\"reason\":null,\"context\":null}')",
    "crash": "raise RuntimeError('boom')",
    "unknown_decision": "print('X4OK {\"v\":1,\"decision\":\"maybe\",\"inert\":false,\"reason\":null,\"context\":null}')",
    "empty": "pass",
    "not_an_object": "print('X4OK [1]')",
    "deny_without_reason": "print('X4OK {\"v\":1,\"decision\":\"deny\",\"inert\":false,\"reason\":null,\"context\":null}')",
}


@pytest.mark.parametrize("stub", sorted(STUBS))
def test_any_adapter_failure_THROWS(oc, stub):
    tk, env = oc
    (tk / ".opencode" / "hooks" / "opencode_adapter.py").write_text("import sys\nsys.stdin.read()\n" + STUBS[stub] + "\n",
                                                                   encoding="utf-8")
    r = drive(tk, env, [before("edit", {"filePath": "dev/mymod/a.xml", "oldString": "a", "newString": "b"})])
    s = r["steps"][0]
    assert s["threw"] and s["message"].startswith("X4 GUARD"), s


def _alive(pid: int) -> bool:
    if WIN:
        r = subprocess.run(["tasklist", "/FI", f"PID eq {pid}", "/NH"], capture_output=True, text=True)
        return str(pid) in r.stdout
    try:
        os.kill(pid, 0)
    except OSError:
        return False
    return True


def test_a_hung_adapter_is_killed_with_its_children_and_THROWS_inert(oc, tmp_path):
    tk, env = oc
    pidfile = tmp_path / "grandchild.pid"
    stub = ("import subprocess, sys, time\n"
            "sys.stdin.read()\n"
            "p = subprocess.Popen([sys.executable, '-c', 'import time; time.sleep(120)'])\n"
            f"open({str(pidfile)!r}, 'w').write(str(p.pid))\n"
            "time.sleep(120)\n")
    (tk / ".opencode" / "hooks" / "opencode_adapter.py").write_text(stub, encoding="utf-8")
    t0 = time.monotonic()
    r = drive(tk, dict(env, X4_OPENCODE_TIMEOUT_S="3"),
              [before("edit", {"filePath": "dev/mymod/a.xml", "oldString": "a", "newString": "b"})])
    took = time.monotonic() - t0
    s = r["steps"][0]
    assert s["threw"] and s["message"].startswith("X4 GUARD INERT") and "timed out" in s["message"], s
    assert took < 3 + 10, f"a 3 s bound took {took:.1f} s"
    pid = int(pidfile.read_text())
    deadline = time.monotonic() + 10
    while _alive(pid) and time.monotonic() < deadline:
        time.sleep(0.3)
    assert not _alive(pid), "the adapter's child survived the timeout: the process TREE was not killed"


